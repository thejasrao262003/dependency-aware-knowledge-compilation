"""Render benchmarks/results/latest.json into the Results section of docs/benchmark.md.

Every number in that section comes from this script; none is written by hand.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STRATS = ("full", "file", "dakc")
SHORT = {
    "S0_no_change": "S0 no change",
    "S1_one_modified": "S1 one source modified",
    "S2_five_modified": "S2 five sources modified",
    "S3_one_deleted": "S3 one source deleted",
    "S4_one_renamed": "S4 one source renamed",
    "S5_one_claim_modified": "S5 one claim modified",
    "S6_new_source_popular_entity": "S6 new source → popular entity",
    "S7_contradiction": "S7 contradicting source",
    "S8_many_pages": "S8 edit touching 7 entities",
    "S9_contradiction_then_delete": "S9 contradiction, then original deleted",
}


def pct(part: float, whole: float) -> str:
    if whole == 0:
        return "—"
    return f"{100 * (1 - part / whole):.1f}%"


def triple(sc: dict, key: str, fmt=str) -> str:
    return " / ".join(fmt(sc["strategies"][s][key]) for s in STRATS)


def render(results: dict) -> str:
    m = results["machine"]
    out = [
        "## Results",
        "",
        "_Generated by `python -m benchmarks.report` from `benchmarks/results/latest.json`._",
        "",
        f"- Date: {m['date']} · {m['platform']} · {m['cpu']} ({m['cpu_count']} cores) · Python {m['python']}",
        f"- Provider: {m['provider']}",
        "- Strategies are run from a copy of the same initial store on the same mutated corpus; "
        "the oracle is an independent full build of the mutated corpus.",
        "- Timing is the median of the stated number of runs. Mock providers have ~0 latency, so times measure "
        "engine overhead (scanning, hashing, SQLite), not LLM latency; LLM calls and tokens are the cost proxy.",
        "",
    ]
    for size in results["sizes"]:
        n = size["n_docs"]
        init = size["initial_build"]
        c = init["counts"]
        out += [
            f"### {n:,} documents",
            "",
            f"Initial full build: {init['seconds']} s, {init['llm_calls']:,} LLM calls; "
            f"{c.get('passage', 0):,} passages, {c.get('claim', 0):,} claims, {c.get('entity', 0):,} entities, "
            f"{c.get('relationship', 0):,} relationships, {c.get('page', 0):,} pages, {c.get('summary', 0):,} summaries, "
            f"{c.get('edges', 0):,} dependency edges. Timing runs per strategy: {size['reps']}.",
            "",
            "**Cost: LLM calls and estimated tokens** (full / file-level / DAKC)",
            "",
            "| Scenario | LLM calls | DAKC saving vs full | DAKC saving vs file-level | Input tokens (est.) | Output tokens (est.) |",
            "|---|---|---|---|---|---|",
        ]
        for key, sc in size["scenarios"].items():
            s = sc["strategies"]
            out.append(
                f"| {SHORT[key]} | {triple(sc, 'llm_calls', lambda v: f'{v:,}')} | "
                f"{pct(s['dakc']['llm_calls'], s['full']['llm_calls'])} | {pct(s['dakc']['llm_calls'], s['file']['llm_calls'])} | "
                f"{triple(sc, 'input_tokens_est', lambda v: f'{v:,}')} | {triple(sc, 'output_tokens_est', lambda v: f'{v:,}')} |"
            )
        out += [
            "",
            "**Work performed** (full / file-level / DAKC)",
            "",
            "| Scenario | Sources processed | Passages re-extracted | Claims regenerated | Pages regenerated (LLM) | Pages re-rendered (no LLM, DAKC) | Summaries regenerated |",
            "|---|---|---|---|---|---|---|",
        ]
        for key, sc in size["scenarios"].items():
            out.append(
                f"| {SHORT[key]} | {triple(sc, 'processed_sources')} | {triple(sc, 'passages_reextracted')} | "
                f"{triple(sc, 'claims_regenerated')} | {triple(sc, 'pages_regenerated')} | "
                f"{sc['strategies']['dakc']['pages_rerendered_no_llm']} | {triple(sc, 'summaries_regenerated')} |"
            )
        out += [
            "",
            "**Correctness and precision against the oracle** (full / file-level / DAKC)",
            "",
            "| Scenario | Artifacts that truly changed (Δ) | Stale artifacts retained | Unnecessary regenerations | Unaffected artifacts modified | Equal to full rebuild |",
            "|---|---|---|---|---|---|",
        ]
        for key, sc in size["scenarios"].items():
            out.append(
                f"| {SHORT[key]} | {sc['oracle_changed_artifacts']:,} | {triple(sc, 'stale_artifacts_retained')} | "
                f"{triple(sc, 'unnecessary_regenerations')} | {triple(sc, 'unaffected_artifacts_modified')} | "
                f"{triple(sc, 'equivalent_to_full_rebuild', lambda v: 'yes' if v else '**NO**')} |"
            )
        out += [
            "",
            "**Execution time, seconds (median)** (full / file-level / DAKC)",
            "",
            "| Scenario | Time |",
            "|---|---|",
        ]
        for key, sc in size["scenarios"].items():
            out.append(f"| {SHORT[key]} | {triple(sc, 'seconds_median', lambda v: f'{v:.3f}')} |")
        if "S1_one_modified" not in size["scenarios"]:
            continue
        s1 = size["scenarios"]["S1_one_modified"]["strategies"]
        rows = [
            ("Number of processed sources", "processed_sources"),
            ("Number of regenerated claims", "claims_regenerated"),
            ("Number of regenerated pages", "pages_regenerated"),
            ("LLM calls", "llm_calls"),
            ("Input tokens (estimated)", "input_tokens_est"),
            ("Output tokens (estimated)", "output_tokens_est"),
            ("Execution time (s, median)", "seconds_median"),
            ("Unaffected artifacts modified", "unaffected_artifacts_modified"),
            ("Incorrectly retained stale artifacts", "stale_artifacts_retained"),
        ]
        out += [
            "",
            f"**PRD comparison table, scenario S1 (one source modified), {n:,} documents**",
            "",
            "| Metric | Full rebuild | File-level invalidation | Incremental (DAKC) |",
            "|---|---|---|---|",
        ]
        for label, k in rows:
            out.append(f"| {label} | {s1['full'][k]:,} | {s1['file'][k]:,} | {s1['dakc'][k]:,} |" if k != "seconds_median"
                       else f"| {label} | {s1['full'][k]:.3f} | {s1['file'][k]:.3f} | {s1['dakc'][k]:.3f} |")
        out.append("")

    out += [
        "### Reading these results",
        "",
        "- **Unaffected artifacts modified is 0 for every strategy, by construction.** A new version is written only when an "
        "artifact's state hash changes, and the mock providers are deterministic, so a needless regeneration reproduces "
        "identical bytes. The column that tells the strategies apart is **unnecessary regenerations**: work whose result was "
        "identical to the previous build. With a real LLM, each of those would also rewrite an unaffected page with different "
        "wording.",
        "- **Stale artifacts retained is 0 for all three strategies.** Inside this engine even the file-level strategy is correct, "
        "because it retracts claims through the same support sets. The audited tools that use file-level invalidation "
        "additionally *merge* LLM output, which keeps retracted facts (research/COMPETITIVE_ANALYSIS.md). That failure mode is "
        "not reproduced here and these numbers do not measure it.",
        "- **Savings depend on corpus structure.** Hub entities (Zipf-distributed mentions) make some single edits touch many "
        "pages. Scenario S8 is the adversarial case where one paragraph mentions seven entities.",
        "- Token counts are **estimates** (mock provider, ceil(chars/4)). No real LLM was called. See *Real LLM providers* above.",
        "",
    ]
    return "\n".join(out)


def p100(x: float) -> str:
    return f"{100 * x:.1f}%"


def render_llm(res: dict, name: str) -> str:
    m = res["machine"]
    out = [
        f"## Real-LLM experiment ({name})",
        "",
        f"_Generated from `benchmarks/results/{name}.json` by `python -m benchmarks.report`._",
        "",
        f"- Model: `{m['provider']}` (temperature 0), date {m['date']}. Token counts are **reported by the provider**, not estimated.",
        "- Harness: `benchmarks/llm_experiment.py`. One model, small corpora: indicative, not a general result about LLMs.",
        "",
    ]
    if "part_a" in res:
        out += [
            "### A. Does editing one sentence disturb the other facts of the paragraph?",
            "",
            "Each paragraph (3+ sentences) is extracted, extracted again unchanged (*repeat stability*), then one fact is "
            "edited (an entity in one sentence replaced by an unseen one) and the new version is processed two ways. "
            "**passage**: the whole paragraph is re-extracted (DAKC's original behaviour). **sentence**: claims of unchanged "
            "sentences are reused verbatim and only changed or context-dependent sentences are sent to the model "
            "(current behaviour), also re-extracting any sentence that may refer back to a changed one (pronouns, \"the X\"). "
            "**sentence-evidence-only**: the same, but trusting only the model's declared sentence dependencies instead of "
            "that pattern rule. *Unchanged-fact reproduction*: claims of untouched sentences kept with identical ids, "
            "which is what lets DAKC skip their pages. *Stale retention*: old claims still stating the replaced detail "
            "(should be 0). *New-fact capture*: paragraphs whose output states the edited fact. Paragraph sets: synthetic "
            "sentences; code-heavy technical notes (`research/audits`); explanatory prose (this repository's design docs); "
            "a coreference set in which the edited sentence is the antecedent of a pronoun in the next sentence.",
            "",
            "| Paragraph set | Paragraphs (failed) | Repeat stability | Mode | Unchanged-fact reproduction ↑ | Stale retention ↓ | New-fact capture ↑ | Output tokens |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for corpus, a in res["part_a"].items():
            for i, mode in enumerate(m for m in ("passage", "sentence", "sentence-evidence-only") if m in a["modes"]):
                r = a["modes"][mode]
                head = (f"{corpus} | {a['paragraphs']} ({a.get('paragraphs_failed', 0)}) | {p100(a['repeat_stability'])}"
                        if i == 0 else " | | ")
                out.append(
                    f"| {head} | {mode} | {p100(r['unchanged_fact_reproduction'])} | {p100(r['stale_retention'])} "
                    f"({r['stale_claims']} of {a.get('detail_claims', 0)}) | {p100(r['new_fact_capture'])} | {r.get('tokens_out', 0):,} |"
                )
        total = sum(a.get("sentences_total", 0) for a in res["part_a"].values())
        for mode in ("sentence", "sentence-evidence-only"):
            sent = sum(a.get("sentences_sent", {}).get(mode, 0) for a in res["part_a"].values())
            if sent:
                out.append("")
                out.append(f"In `{mode}` mode, {p100(sent / max(1, total))} of all sentences were sent to the model; the rest of each paragraph was reused.")
        ex = [e for a in res["part_a"].values() for e in (a.get("stale_examples") or [])]
        if ex:
            out += ["", "Stale claims observed (old detail kept after the edit):", ""]
            out += [f"- `{e['mode']}`: edited *{e['edited_sentence'][:150]}* → kept *{'; '.join(e['stale_claim_kept'])[:150]}*" for e in ex[:6]]
        fails = [f for a in res["part_a"].values() for f in (a.get("failures") or [])]
        if fails:
            out += ["", "Provider failures: " + "; ".join(sorted(set(fails))[:5])]
        out.append("")
    if "part_b" in res:
        b = res["part_b"]
        f = b["full_build"]
        out += [
            f"### B. End-to-end incremental compilation, {b['n_docs']} synthetic documents",
            "",
            f"Full build with the real model: {f['llm_calls']:,} LLM calls, {f['input_tokens']:,} input / {f['output_tokens']:,} "
            f"output tokens, {f['seconds']} s. Each scenario then starts from a copy of that store."
            + (f" Provenance of the LLM-written pages: {f['citation_coverage']['cited']} of {f['citation_coverage']['sentences']} "
               f"generated sentences ({p100(f['citation_coverage']['coverage'])}) cite at least one claim, with "
               f"{f['citation_coverage']['invalid_markers']} invalid citations; `provenance = \"strict\"` renders only the cited ones."
               if f.get("citation_coverage") else ""),
            "",
            "| Scenario | Run | LLM calls | Tokens in / out | Claims new / retracted | Pages regenerated | Re-rendered (no LLM) | Seconds | Invariants |",
            "|---|---|---|---|---|---|---|---|---|",
        ]
        s5 = []
        order = ["file", "dakc-passage", "dakc"]
        for key, sc in b["scenarios"].items():
            for run in sorted(sc["runs"], key=lambda r: order.index(r) if r in order else 99):
                r = sc["runs"][run]
                if r.get("status") == "failed":
                    out.append(f"| {SHORT[key]} | {run} | failed ({r['error']}) | | | | | | {'pass' if r['invariants_pass'] else 'FAIL'} |")
                    continue
                out.append(
                    f"| {SHORT[key]} | {run} | {r['llm_calls']} | {r['input_tokens']:,} / {r['output_tokens']:,} | "
                    f"{r['claims_new']} / {r['claims_retracted']} | {r['pages_regenerated']} | {r['pages_rerendered_no_llm']} | "
                    f"{r['seconds']} | {'pass' if r['invariants_pass'] else '**FAIL**'} |"
                )
                if "old_value_still_claimed_by_doc" in r:
                    s5.append((run, r))
        if s5:
            change = b["scenarios"]["S5_one_claim_modified"]["change"].get("claim", "")
            out += ["", f"**Did the edited value actually change?** Scenario S5 edits `{change}`.", "",
                    "| Run | Old value still claimed by the edited document ↓ | New value present ↑ |", "|---|---|---|"]
            out += [f"| {run} | {'**yes (stale)**' if r['old_value_still_claimed_by_doc'] else 'no'} | {'yes' if r['new_value_claimed'] else '**no**'} |" for run, r in s5]
        out.append("")
    return "\n".join(out)


def render_equivalence(eq: dict) -> str:
    names = {"exact": "exact (DAKC claim identity)", "fuzzy": "naive fuzzy (token_sort_ratio ≥ 85)",
             "guarded": "guarded deterministic (`dakc duplicates`)", "llm": f"LLM judge (`{eq.get('llm_model', '')}`)"}
    out = [
        "## Claim equivalence: can paraphrases be matched without false merges?",
        "",
        "_Generated from `benchmarks/results/equivalence.json` (`python -m benchmarks.equivalence`)._",
        "",
        f"{eq['pairs']} labelled pairs: {eq['positives']} paraphrases of the same fact, and hard negatives where the value "
        "changed, the subject or object was swapped, the direction was reversed, the relation changed, or the statement "
        "was negated. A false merge would silently turn two different facts into one, so precision matters most.",
        "",
        "| Matcher | Precision | Recall | False merges |",
        "|---|---|---|---|",
    ]
    for k, m in eq["matchers"].items():
        out.append(f"| {names.get(k, k)} | {p100(m['precision'])} | {p100(m['recall'])} | {m['false_merges']} |")
    fz = eq["matchers"].get("fuzzy", {}).get("by_type", {})
    if fz:
        out += ["", "Naive fuzzy matching merged: " + ", ".join(f"{t} {v['matched']}/{v['pairs']}" for t, v in sorted(fz.items()) if t != "paraphrase" and v["matched"]) + "."]
    out += [
        "",
        "**Policy.** Claim identity stays exact (normalized text), because dependency correctness cannot rest on a "
        "similarity score or a model's judgement. The guarded matcher is shipped only as an advisory report "
        "(`dakc duplicates`); nothing is merged. The pairs are templated, so these numbers are an optimistic bound for "
        "real text, particularly for the LLM judge.",
        "",
    ]
    return "\n".join(out)


README_START = "<!-- BENCHMARK:START (generated by python -m benchmarks.report) -->"
README_END = "<!-- BENCHMARK:END -->"


def readme_summary(results: dict, scale: dict | None = None) -> str:
    big = max(results["sizes"], key=lambda s: s["n_docs"])
    n = big["n_docs"]
    lines = [
        README_START,
        "### Deterministic benchmark (mock provider)",
        "",
        f"Seeded synthetic corpus, **{n:,} documents** ({big['initial_build']['counts'].get('claim', 0):,} claims, "
        f"{big['initial_build']['counts'].get('page', 0):,} pages, {big['initial_build']['counts'].get('edges', 0):,} dependency edges). "
        "Deterministic mock provider: LLM calls are counted exactly, tokens are estimated. All three strategies run in the same "
        "engine. *File-level* emulates the strategy of existing LLM-wiki tools.",
        "",
        "| Scenario | Input tokens (est.): full / file-level / DAKC | LLM calls: full / file-level / DAKC | Pages regenerated: full / file-level / DAKC | Equal to full rebuild (DAKC) |",
        "|---|---|---|---|---|",
    ]
    for key, sc in big["scenarios"].items():
        s = sc["strategies"]
        lines.append(
            f"| {SHORT[key]} | {s['full']['input_tokens_est']:,} / {s['file']['input_tokens_est']:,} / "
            f"**{s['dakc']['input_tokens_est']:,}** | {s['full']['llm_calls']:,} / {s['file']['llm_calls']:,} / **{s['dakc']['llm_calls']:,}** | "
            f"{s['full']['pages_regenerated']:,} / {s['file']['pages_regenerated']:,} / **{s['dakc']['pages_regenerated']:,}** | "
            f"{'yes' if s['dakc']['equivalent_to_full_rebuild'] and s['dakc']['stale_artifacts_retained'] == 0 else '**NO**'} |"
        )
    all_eq = all(
        st["equivalent_to_full_rebuild"] and st["stale_artifacts_retained"] == 0
        for size in results["sizes"] for sc in size["scenarios"].values() for st in sc["strategies"].values()
    )
    no_waste = all(
        sc["strategies"]["dakc"]["unnecessary_regenerations"] == 0
        for size in results["sizes"] for sc in size["scenarios"].values()
    )
    sizes = ", ".join(f"{s['n_docs']:,}" for s in results["sizes"])
    why = {
        "S7_contradiction": "a brand-new fact must be extracted and written under any strategy",
        "S3_one_deleted": "retracted facts genuinely require regenerating the pages that stated them",
        "S6_new_source_popular_entity": "new facts about a hub entity must reach its page under any strategy",
    }
    savings = sorted(
        (1 - sc["strategies"]["dakc"]["input_tokens_est"] / sc["strategies"]["file"]["input_tokens_est"], key)
        for key, sc in big["scenarios"].items() if sc["strategies"]["file"]["input_tokens_est"]
    )
    smallest = "; ".join(
        f"{SHORT[k]}: {100 * s:.0f}%" + (f" ({why[k]})" if k in why else "") for s, k in savings[:2]
    )
    lines += [
        "",
        f"Across all sizes ({sizes} documents) and scenarios, every strategy's result was "
        f"{'identical to an independent full rebuild' if all_eq else '**not always** identical to a full rebuild'}, and DAKC "
        f"{'never regenerated an artifact whose inputs were unchanged' if no_waste else '**did** regenerate some unchanged artifacts'}. "
        f"The smallest input-token savings versus file-level at {n:,} documents: {smallest}. "
        "Compare tokens rather than calls: every strategy writes hub pages and large topics in sections, so "
        "rebuilding one of them file-level is many small calls. "
        "Full tables, method and caveats are in [docs/benchmark.md](docs/benchmark.md). Raw data: "
        "[benchmarks/results/latest.json](benchmarks/results/latest.json).",
    ]
    if scale:
        for size in scale["sizes"]:
            c = size["initial_build"]["counts"]
            eq = all(
                st["equivalent_to_full_rebuild"] and st["stale_artifacts_retained"] == 0
                for sc in size["scenarios"].values() for st in sc["strategies"].values()
            )
            per = "; ".join(
                f"{SHORT[k]} {sc['strategies']['full']['llm_calls']:,} / {sc['strategies']['file']['llm_calls']:,} / "
                f"**{sc['strategies']['dakc']['llm_calls']:,}**"
                for k, sc in size["scenarios"].items()
            )
            lines += [
                "",
                f"**At {size['n_docs']:,} documents** ({scale.get('profile', 'uniform')} length and topic distributions; "
                f"{c.get('claim', 0):,} claims, {c.get('page', 0):,} pages, {c.get('edges', 0):,} dependency edges), "
                f"LLM calls full / file-level / DAKC: {per}. Every strategy was "
                f"{'identical to a full rebuild with 0 stale artifacts' if eq else '**not always** identical to a full rebuild'}. "
                "Raw data: [benchmarks/results/scale-realistic.json](benchmarks/results/scale-realistic.json).",
            ]
    for llm_path in sorted((ROOT / "benchmarks" / "results").glob("llm-*.json")):
        llm = json.loads(llm_path.read_text(encoding="utf-8"))
        model = llm["machine"]["provider"].split(":", 1)[-1].strip()
        if "part_b" in llm:
            b = llm["part_b"]
            lines += [
                "",
                "### Real-model measurements",
                "",
                f"`{model}`, {b['n_docs']} synthetic documents (full build: "
                f"{b['full_build']['llm_calls']} calls, {b['full_build']['input_tokens']:,} input tokens). "
                "Calls and tokens are provider-reported; hosted models are not deterministic, so these are indicative:",
                "",
                "| Scenario | LLM calls: file-level / DAKC | Input tokens: file-level / DAKC | Pages regenerated: file-level / DAKC |",
                "|---|---|---|---|",
            ]
            for key, sc in b["scenarios"].items():
                f, d = sc["runs"].get("file", {}), sc["runs"].get("dakc", {})
                if "llm_calls" in f and "llm_calls" in d:
                    lines.append(f"| {SHORT[key]} | {f['llm_calls']} / **{d['llm_calls']}** | {f['input_tokens']:,} / **{d['input_tokens']:,}** | {f['pages_regenerated']} / **{d['pages_regenerated']}** |")
        if "part_a" in llm:
            rows = llm["part_a"]
            parts = []
            for corpus in ("technical", "prose", "coreference"):
                if corpus in rows:
                    m = rows[corpus]["modes"]
                    parts.append(
                        f"{corpus}: {p100(m['passage']['unchanged_fact_reproduction'])} → **{p100(m['sentence']['unchanged_fact_reproduction'])}** "
                        f"(stale {m['passage']['stale_claims']} → {m['sentence']['stale_claims']})"
                    )
            if parts:
                lines += [
                    "",
                    "Unchanged facts kept with identical claim ids after a one-sentence edit, whole-paragraph re-extraction → "
                    "sentence reuse: " + "; ".join(parts) + ". See *Real-LLM experiment* in docs/benchmark.md.",
                ]
    lines.append(README_END)
    return "\n".join(lines)


def main() -> None:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "benchmarks" / "results" / "latest.json"
    doc = ROOT / "docs" / "benchmark.md"
    results = json.loads(src.read_text(encoding="utf-8"))
    text = doc.read_text(encoding="utf-8")
    head = text.split("## Results", 1)[0].rstrip() + "\n\n"
    body = render(results)
    scale = ROOT / "benchmarks" / "results" / "scale-realistic.json"
    sc = None
    if scale.exists():
        sc = json.loads(scale.read_text(encoding="utf-8"))
        body += "\n" + render(sc).replace("## Results", "## Scale run: realistic document distributions", 1).replace(
            "benchmarks/results/latest.json", "benchmarks/results/scale-realistic.json", 1).split("### Reading these results")[0]
    for llm in sorted((ROOT / "benchmarks" / "results").glob("llm-*.json")):
        body += "\n" + render_llm(json.loads(llm.read_text(encoding="utf-8")), llm.stem)
    eq = ROOT / "benchmarks" / "results" / "equivalence.json"
    if eq.exists():
        body += "\n" + render_equivalence(json.loads(eq.read_text(encoding="utf-8")))
    doc.write_text(head + body, encoding="utf-8")
    print(f"updated {doc}")

    readme = ROOT / "README.md"
    rtext = readme.read_text(encoding="utf-8")
    block = readme_summary(results, sc)
    if README_START in rtext:
        pre, rest = rtext.split(README_START, 1)
        rtext = pre + block + rest.split(README_END, 1)[1]
    else:
        rtext = rtext.replace("BENCHMARK_SUMMARY_PLACEHOLDER", block)
    readme.write_text(rtext, encoding="utf-8")
    print(f"updated {readme}")


if __name__ == "__main__":
    main()
