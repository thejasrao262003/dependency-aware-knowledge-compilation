"""A real agent maintaining and querying the FastAPI knowledge base over MCP.

Runs Claude Code headless (``claude -p``) with every built-in tool disabled and
only the DAKC MCP server configured, so the agent can do nothing except use
DAKC's tools. Two sessions, around one real commit
(fastapi/fastapi@b0a616d9, "Add configurable form parsing limits"):

  before  the docs at the commit's parent: ask the question
  after   the docs at the commit: "I pulled the latest docs; update the
          knowledge base (preview first), then answer again"

The tool calls and answers are written to results/agent-session.md. Requires
the `claude` CLI, logged in. Running it uses your Claude usage (about $0.20).

Usage: python examples/fastapi-docs/agent_session.py [--model sonnet]
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from replay import DOCS, ensure_clone, git  # noqa: E402

import dakc  # noqa: E402

FEATURED = "b0a616d9"
QUESTION = ("What happens when a form upload exceeds FastAPI's parsing limits, and how can I limit the number of "
            "uploaded files? Answer from the knowledge base and cite the source document for each point.")
PROMPTS = {
    "before": QUESTION,
    "after": ("I just pulled the latest FastAPI docs. Bring the knowledge base up to date, but show me what will change "
              "before you build. Then answer again: " + QUESTION),
}


def run_agent(prompt: str, mcp_config: Path, model: str, cwd: Path) -> dict:
    cmd = ["claude", "-p", prompt, "--model", model, "--tools", "", "--strict-mcp-config", "--mcp-config", str(mcp_config),
           "--allowedTools", "mcp__dakc", "--setting-sources", "project", "--no-session-persistence",
           "--output-format", "stream-json", "--verbose", "--max-turns", "30"]
    proc = subprocess.run(cmd, capture_output=True, text=True, cwd=cwd, timeout=900)
    calls, errors, final = [], {}, {}
    for line in proc.stdout.splitlines():
        if not line.startswith("{"):
            continue
        e = json.loads(line)
        if e.get("type") == "assistant":
            for c in e["message"].get("content", []):
                if c.get("type") == "tool_use":
                    calls.append({"id": c["id"], "tool": c["name"].removeprefix("mcp__dakc__"), "input": c["input"]})
        elif e.get("type") == "user" and isinstance(e["message"].get("content"), list):
            for c in e["message"]["content"]:
                if c.get("type") == "tool_result" and c.get("is_error"):
                    errors[c["tool_use_id"]] = True
        elif e.get("type") == "result":
            final = e
    return {"calls": [{"tool": c["tool"], "input": c["input"], "error": errors.get(c["id"], False)} for c in calls],
            "answer": final.get("result", ""), "turns": final.get("num_turns"), "cost_usd": final.get("total_cost_usd")}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default="sonnet")
    args = ap.parse_args()
    work = HERE / ".work"
    repo = ensure_clone(work)
    sha = git(repo, "rev-parse", FEATURED).strip()
    ws = work / "agent-kb"
    shutil.rmtree(ws, ignore_errors=True)
    ws.mkdir(parents=True)
    (ws / "dakc.toml").write_text(f'[dakc]\nsource_dir = "../fastapi/{DOCS}"\nprovider = "mock"\n', encoding="utf-8")
    mcp = work / "agent-mcp.json"
    mcp.write_text(json.dumps({"mcpServers": {"dakc": {"command": sys.executable,
                                                       "args": ["-m", "dakc", "mcp", "--workspace", str(ws)]}}}))

    git(repo, "checkout", "-q", f"{sha}^")
    with dakc.open(ws) as kb:
        kb.compile()
    sessions = {"before": run_agent(PROMPTS["before"], mcp, args.model, work)}
    git(repo, "checkout", "-q", sha)
    sessions["after"] = run_agent(PROMPTS["after"], mcp, args.model, work)

    out = ["# A real agent on the FastAPI knowledge base, over MCP", "",
           f"_Generated by `examples/fastapi-docs/agent_session.py`: Claude Code (`{args.model}`) headless, built-in tools "
           "disabled, only the DAKC MCP server available. The answers are the agent's own, unedited._", ""]
    for name, title in (("before", f"Before commit `{sha[:8]}`"), ("after", f"After pulling commit `{sha[:8]}`")):
        s = sessions[name]
        out += [f"## {title}", "", f"**Prompt:** {PROMPTS[name]}", "", "**Tool calls:**", ""]
        out += [f"{i}. `{c['tool']}({json.dumps(c['input'])})`" + (" (error)" if c["error"] else "")
                for i, c in enumerate(s["calls"], 1)]
        out += ["", "**Answer:**", "", *[f"> {line}" if line else ">" for line in s["answer"].splitlines()], "",
                f"_{s['turns']} turns, ${s['cost_usd']:.2f}._", ""]
    (HERE / "results").mkdir(exist_ok=True)
    (HERE / "results" / "agent-session.md").write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {HERE / 'results' / 'agent-session.md'}")


if __name__ == "__main__":
    main()
