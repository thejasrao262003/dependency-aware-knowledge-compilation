"""Conflict detection on FastAPI's real documentation, captured as it runs.

FastAPI changed its password-hashing advice in 0.118.0 (fastapi/fastapi@efdafa43): the
security tutorial moved from PassLib with "Bcrypt" to pwdlib with "Argon2". A team that
copied the earlier docs into its own notes still says Bcrypt. Steps:

  1. One knowledge base from two sources: FastAPI's docs (pinned commit) and the team's notes.
  2. A pull request copies the pre-0.118.0 advice into the notes. `dakc review`, the
     pull-request comment, reports that it introduces a conflict.
  3. It is merged anyway. `dakc compile` reports the conflict; `dakc conflicts` lists it.
  4. `dakc explain cfl:...` shows both sentences, with file and line, and the pages built on them.
  5. `dakc conflicts --check` fails CI while it is open.
  6. The team marks the section as history ("Before FastAPI 0.118.0"). The difference is
     now scoped, not a conflict.
  7. `dakc verify`: the stored findings equal a detection from scratch.

Every command's real output is written to results/conflicts-walkthrough.md. It uses the
deterministic mock provider, so nothing is sent to a model.

Usage: python examples/fastapi-docs/conflicts_walkthrough.py   (clones FastAPI's docs if needed)
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from replay import DOCS, END, ensure_clone, git  # noqa: E402

import dakc  # noqa: E402

SWITCH = "efdafa43"  # "Update tutorial/security/oauth2-jwt/ to use pwdlib with Argon2 instead of passlib"
TOML = """[dakc]
provider = "mock"

[[sources]]                 # FastAPI's documentation, at its own paths
name = "fastapi"
type = "filesystem"
path = "fastapi-docs"
prefix = ""

[[sources]]                 # the team's own notes, under team/
name = "team"
type = "filesystem"
path = "team-notes"
"""
NOTES = """# Auth notes

Our services follow the FastAPI security tutorial for login.

Access tokens are JWTs signed with a secret key.
"""
COPIED = """
## Password hashing

PassLib is a great Python package to handle password hashes.

The recommended algorithm is "Bcrypt".
"""
HISTORY = """
## Password hashing

### Before FastAPI 0.118.0

PassLib is a great Python package to handle password hashes.

The recommended algorithm is "Bcrypt".
"""


def main() -> None:
    work = HERE / ".work"
    repo = ensure_clone(work)
    switch = git(repo, "rev-parse", SWITCH).strip()
    release = git(repo, "tag", "--contains", switch, "--sort=v:refname").split()[0]
    ws = work / "conflicts-walkthrough"
    shutil.rmtree(ws, ignore_errors=True)
    (ws / "fastapi-docs").mkdir(parents=True)
    archive = subprocess.run(["git", "-C", str(repo), "archive", END, DOCS], check=True, capture_output=True).stdout
    subprocess.run(["tar", "-x", "--strip-components=3", "-C", str(ws / "fastapi-docs")], input=archive, check=True)
    (ws / "team-notes").mkdir()
    notes = ws / "team-notes" / "auth.md"
    notes.write_text(NOTES, encoding="utf-8")
    (ws / "dakc.toml").write_text(TOML, encoding="utf-8")
    (ws / ".gitignore").write_text(".dakc/\nwiki/\n", encoding="utf-8")

    def sh(*cmd: str) -> str:  # git in the demo repository, with a neutral identity (never pushed)
        return subprocess.run(["git", "-c", "user.name=Demo", "-c", "user.email=demo@example.invalid", *cmd], cwd=ws,
                              check=True, capture_output=True, text=True).stdout

    sh("init", "-q", "-b", "main")
    sh("add", "-A")
    sh("commit", "-q", "-m", "FastAPI docs and our auth notes")

    out: list[str] = []
    env = {**os.environ, "COLUMNS": "120"}

    def section(title: str, text: str = "") -> None:
        out.extend([f"## {title}", "", text, ""] if text else [f"## {title}", ""])

    def run(*cmd: str, quiet: bool = False) -> tuple[str, int]:
        proc = subprocess.run([sys.executable, "-m", "dakc", *cmd, "-w", str(ws)], capture_output=True, text=True, env=env)
        text = (proc.stdout + proc.stderr).rstrip().replace(str(work), ".work")
        if not quiet:
            out.extend([f"```console\n$ dakc {' '.join(cmd)}\n{text}\n```", ""])
        return text, proc.returncode

    def show(path: Path) -> None:
        out.extend([f"`{path.relative_to(ws).as_posix()}`:", "", "```markdown", path.read_text(encoding="utf-8").rstrip(), "```", ""])

    out += [
        "# Walkthrough: conflicting documents, caught and resolved",
        "",
        f"_Generated by `examples/fastapi-docs/conflicts_walkthrough.py` (DAKC {dakc.__version__}). Every output below is "
        "real and unedited apart from shortened paths. Nothing is sent to a model._",
        "",
        f"In {release} FastAPI changed its password-hashing advice: [`{switch[:8]}`](https://github.com/fastapi/fastapi/commit/{switch}) "
        "moved the security tutorial from PassLib with \"Bcrypt\" to pwdlib with \"Argon2\". Any notes a team copied from "
        "the earlier docs still say Bcrypt, and nothing tells them. This walkthrough puts a team's notes and FastAPI's docs "
        f"(at [`{END[:8]}`](https://github.com/fastapi/fastapi/tree/{END}/{DOCS})) in one knowledge base.",
        "",
    ]

    # 1
    section("1. One knowledge base, two sources", "FastAPI's 159 documentation pages keep their paths; the team's notes "
            "appear under `team/`.")
    out.extend(["`dakc.toml`:", "", "```toml", TOML.rstrip(), "```", ""])
    show(notes)
    text, _ = run("compile", quiet=True)
    with dakc.open(ws) as kb:
        c, n_conf = kb.store.counts(), len(kb.conflicts(scoped=True))
    out += [f"`dakc compile`: {c['source']} documents, {c['claim']:,} claims, {c['page']:,} entity pages. "
            f"**{n_conf} conflicts.**", ""]

    # 2
    sh("checkout", "-q", "-b", "add-hashing-notes")
    notes.write_text(NOTES + COPIED, encoding="utf-8")
    sh("commit", "-q", "-am", "Add password hashing notes")
    section("2. A pull request copies the old advice",
            f"A teammate adds a section from FastAPI's docs as they were before {release}, word for word:")
    out.extend(["```diff", *("+" + line for line in COPIED.strip("\n").splitlines()), "```", ""])
    comment, _ = run("review", "--base", "main", quiet=True)
    lines = [line for line in comment.splitlines() if not line.startswith("<!--")]  # the comment's update marker
    out += ["The GitHub Action posts `dakc review --base main` on the pull request. This is that comment, as it renders:",
            "", *("> " + line if line else ">" for line in lines), ""]

    # 3
    sh("checkout", "-q", "main")
    sh("merge", "-q", "--ff-only", "add-hashing-notes")
    section("3. Merged anyway: the compile reports it")
    text, _ = run("compile", quiet=True)
    kept = [line for line in text.splitlines() if line.startswith(("Conflicts:", "LLM Calls"))]
    out.extend(["```console", "$ dakc compile", "...", *kept, "```", ""])
    run("conflicts")

    # 4
    with dakc.open(ws) as kb:
        (conflict,) = kb.conflicts()
    section("4. Where, exactly", "Both sentences, the file and line of each, the heading and scope they sit under, and "
            "the pages and summaries built from them:")
    run("explain", conflict.id)

    # 5
    section("5. A gate for CI")
    _, code = run("conflicts", "--check", quiet=True)
    out.extend(["```console", "$ dakc conflicts --check > /dev/null; echo $?", str(code), "```", "",
                "Detection is advisory: both claims stay on their pages, each citing its own source. DAKC never decides "
                "which document is right.", ""])

    # 6
    notes.write_text(NOTES + HISTORY, encoding="utf-8")
    sh("commit", "-q", "-am", "Mark the Bcrypt advice as history")
    section("6. Resolve it",
            "The team keeps the old advice, as history: the same sentences, under a heading that says when they applied.")
    out.extend(["```diff", " ## Password hashing", " ", f"+### Before FastAPI {release}", "+", " PassLib is a great Python "
                "package to handle password hashes.", "```", ""])
    text, _ = run("compile", quiet=True)
    out.extend(["```console", "$ dakc compile", "...",
                *[line for line in text.splitlines() if line.startswith("Conflicts:")], "```", ""])
    run("conflicts", "--all")
    shown, _ = run("explain", conflict.id, quiet=True)
    out.extend(["```console", f"$ dakc explain {conflict.id}",
                *[line for line in shown.splitlines() if line.startswith(("Scoped", "Property", "Why"))], "...", "```", ""])
    out += [f"The two values now apply to different scopes: \"{release}\" in the heading puts the Bcrypt advice in its own "
            "release, so it is listed as a *scoped* difference, not a conflict. Editing the notes to say Argon2, or deleting "
            "the section, would close it too.", ""]

    # 7
    section("7. Checked")
    verify, _ = run("verify", quiet=True)
    out.extend(["```console", "$ dakc verify", *[line for line in verify.splitlines() if "conflict" in line.lower()
                                                  or line.startswith(("PASS  equal", "PASS  wiki"))], "```", "",
                "The findings kept by incremental builds equal a detection from scratch over every claim.", ""])

    path = HERE / "results" / "conflicts-walkthrough.md"
    path.parent.mkdir(exist_ok=True)
    path.write_text("\n".join(out).rstrip() + "\n", encoding="utf-8")
    print(f"wrote {path}")
    print(json.dumps({"conflict": conflict.id, "release": release}))


if __name__ == "__main__":
    main()
