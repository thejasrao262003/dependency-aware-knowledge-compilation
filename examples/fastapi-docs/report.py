"""Render results/replay.json (from replay.py) as results/replay.md.

Usage: python examples/fastapi-docs/report.py
"""

from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def group(rows: list[dict], label: str) -> str:
    t = {s: {k: sum(r[s][k] for r in rows) for k in ("llm_calls", "input_tokens_est", "pages_regenerated")}
         for s in ("full", "file", "dakc")}
    return (f"| {label} ({len(rows)}) | {t['full']['llm_calls']:,} | {t['file']['llm_calls']:,} | **{t['dakc']['llm_calls']:,}** | "
            f"{t['file']['pages_regenerated']:,} | **{t['dakc']['pages_regenerated']:,}** | "
            f"{t['file']['input_tokens_est']:,} | **{t['dakc']['input_tokens_est']:,}** |")


def main() -> None:
    d = json.loads((HERE / "results" / "replay.json").read_text(encoding="utf-8"))
    rows = d["commits"]
    notes_only = [r for r in rows if r["files"] == ["release-notes.md"]]
    content = [r for r in rows if r["files"] != ["release-notes.md"]]
    ib = d["initial_build"]
    c = ib["counts"]
    src = d["source"]
    t = d["totals"]
    lines = [
        "# Replay: 50 real commits to FastAPI's documentation",
        "",
        f"_Generated by `examples/fastapi-docs/report.py` from `results/replay.json` ({d['generated']}, DAKC {d['dakc_version']})._",
        "",
        f"- **Corpus.** [{src['path']}]({src['repository'].removesuffix('.git')}/tree/{src['end']}/{src['path']}) "
        f"({src['license']} license): {c['source']} documents, {c['passage']:,} passages, {c['claim']:,} claims, "
        f"{c['page']:,} entity pages, {c['edges']:,} dependency edges. A full build is {ib['llm_calls']:,} LLM calls.",
        f"- **Commits.** The last {len(rows)} commits that changed the docs, up to "
        f"[`{src['end'][:8]}`]({src['repository'].removesuffix('.git')}/commit/{src['end']}), replayed in order.",
        f"- **Provider.** {d['provider']}. The calls are exactly what each strategy would send to an LLM.",
        "- **Strategies.**",
        "  - *full*: rebuild everything.",
        "  - *file*: re-process every changed file, as file-level LLM-wiki tools do.",
        "  - *dakc*: incremental, carrying the knowledge base from commit to commit.",
        "  - All three run in the same engine.",
        f"- **Correctness.** After every commit, DAKC's incrementally maintained state was compared with an independent "
        f"full rebuild: **{'identical at all ' + str(len(rows)) + ' commits' if d['all_equal_to_full_rebuild'] else 'NOT always identical'}**.",
        "",
        "## Totals",
        "",
        "| Commits | LLM calls: full | file | DAKC | Pages regenerated: file | DAKC | Input tokens (est.): file | DAKC |",
        "|---|---|---|---|---|---|---|---|",
        group(rows, "All"),
        group(notes_only, "Only `release-notes.md` changed"),
        group(content, "Docs content changed"),
        "",
        f"Across all {len(rows)} commits:",
        "",
        f"- **LLM calls:** DAKC {t['dakc']['llm_calls']:,}, re-processing changed files {t['file']['llm_calls']:,}, "
        f"full rebuilds {t['full']['llm_calls']:,}.",
        f"- **Estimated input tokens:** DAKC {t['dakc']['input_tokens_est']:,}, file-level {t['file']['input_tokens_est']:,} "
        f"({t['file']['input_tokens_est'] / t['dakc']['input_tokens_est']:.1f} times as many). The token gap is much smaller "
        "than the call gap; the next section explains why.",
        "",
        "### Why the totals look like this",
        "",
        f"- **The release notes.** {len(notes_only)} of the {len(rows)} commits only append a line or two to "
        "`release-notes.md`, an 8,000-line file. Most of those commits are made by a bot.",
        "  - A file-level tool re-processes the whole file every time: about 5,800 LLM calls and 1,569 pages per commit.",
        "  - DAKC re-extracts the new paragraph and regenerates the few pages it touches: 0 to 6 calls.",
        "  - Most of the total difference comes from this pattern. It is common in real repositories: changelogs,",
        "    ADR logs and meeting notes.",
        "- **Content edits.** The other commits change docs pages, and there the difference is smaller:",
    ]
    for r in content:
        lines.append(f"  - `{r['commit'][:8]}` \"{r['subject'][:70]}\" (+{r['lines_added']}/-{r['lines_removed']} lines in "
                     f"{len(r['files'])} file(s)): {r['file']['llm_calls']:,} calls file-level, "
                     f"**{r['dakc']['llm_calls']:,} DAKC**.")
    lines += [
        "  - When a commit is mostly new text in one file, the two converge, because new text has to be extracted under",
        "    any strategy.",
        "  - When it changes a few lines across files, or a few lines in a long page, DAKC does several times less work.",
        "- **Where DAKC's tokens go.** Almost all of DAKC's tokens are spent on one artifact: the summary of the docs root",
        "  folder, which lists about 1,660 pages.",
        "  - Every commit that changes a page in that folder regenerates the summary, with a prompt of about 55,000",
        "    tokens.",
        "  - A topic summary's prompt grows with the size of its folder. This is DAKC's most expensive artifact on large,",
        "    flat folders, and a known limitation (see Limitations in the main README).",
        "",
        "## Every commit",
        "",
        "| # | Commit | Date | Change | LLM calls: full / file / DAKC | Pages: file / DAKC | Equal to full rebuild |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        change = f"+{r['lines_added']}/-{r['lines_removed']} in " + (", ".join(r["files"]) if len(r["files"]) <= 2 else f"{len(r['files'])} files")
        lines.append(f"| {r['n']} | [`{r['commit'][:8]}`]({src['repository'].removesuffix('.git')}/commit/{r['commit']}) | {r['date']} | {change} | "
                     f"{r['full']['llm_calls']:,} / {r['file']['llm_calls']:,} / **{r['dakc']['llm_calls']:,}** | "
                     f"{r['file']['pages_regenerated']:,} / **{r['dakc']['pages_regenerated']:,}** | "
                     f"{'yes' if r['equal_to_full_rebuild'] else '**NO**'} |")
    (HERE / "results" / "replay.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {HERE / 'results' / 'replay.md'}")


if __name__ == "__main__":
    main()
