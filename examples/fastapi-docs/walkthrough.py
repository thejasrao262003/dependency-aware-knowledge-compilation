"""The DAKC walkthrough on FastAPI's real documentation, captured as it runs.

Uses one real commit, fastapi/fastapi@b0a616d9 ("Add configurable form parsing
limits"), which adds a section to one existing docs page. Steps:

  1. Compile a knowledge base from the 159 English docs pages just before it.
  2. Ask: what happens when a form exceeds FastAPI's parser limits? (not documented yet)
  3. Apply the real commit.
  4. `dakc compile --dry-run`: exactly what the edit invalidates, before anything runs.
  5. `dakc compile`: incremental build.
  6. Ask again, and `dakc trace` the answer to the source sentence.
  7. `dakc verify --against-full`: the result equals a from-scratch rebuild.

Every command's real output is written to results/walkthrough.md. The mock
provider produces the same knowledge as the free heuristic provider but counts
each call an LLM provider would make, so the numbers show what a real model
would be asked to do.

Usage: python examples/fastapi-docs/walkthrough.py   (after replay.py, or it clones FastAPI itself)
"""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from replay import DOCS, ensure_clone, git  # noqa: E402

import dakc  # noqa: E402

FEATURED = "b0a616d9"
QUESTION = "parser limit"  # the reader asks: what happens when a form exceeds FastAPI's parser limits?


def main() -> None:
    work = HERE / ".work"
    repo = ensure_clone(work)
    sha = git(repo, "rev-parse", FEATURED).strip()
    parent = git(repo, "rev-parse", f"{sha}^").strip()
    ws = work / "walkthrough-kb"
    shutil.rmtree(ws, ignore_errors=True)
    ws.mkdir(parents=True)
    out: list[str] = []

    def section(title: str, text: str = "") -> None:
        out.extend([f"## {title}", "", text] if text else [f"## {title}", ""])

    def run(*cmd: str, show: str | None = None, json_out: bool = False):
        proc = subprocess.run([sys.executable, "-m", "dakc", *cmd, "-w", str(ws)], capture_output=True, text=True,
                              env={**__import__("os").environ, "COLUMNS": "120"})
        text = (proc.stdout + proc.stderr).rstrip().replace(str(work), ".work")
        if json_out:
            return json.loads(proc.stdout)
        out.extend([f"```console\n$ dakc {show or ' '.join(cmd)}\n{text}\n```", ""])
        return text

    def ask(label: str) -> list[dakc.ArtifactSummary]:
        with dakc.open(ws) as kb:
            hits = kb.artifacts("claim", query=QUESTION, limit=10)
        lines = [f"- `{h.id}`: {h.title}" for h in hits] or ["- *(nothing: the docs do not cover it yet)*"]
        out.extend([f"**{label}** Facts (claims) mentioning \"{QUESTION}\":", "", *lines, ""])
        return hits

    out += [
        "# Walkthrough: DAKC on FastAPI's documentation",
        "",
        f"_Generated by `examples/fastapi-docs/walkthrough.py` (DAKC {dakc.__version__}). Every output below is real and "
        "unedited apart from shortened paths._",
        "",
        f"FastAPI's English docs (MIT licensed) at [`{parent[:8]}`](https://github.com/fastapi/fastapi/tree/{parent}/{DOCS}), "
        f"then one real commit: [`{sha[:8]}`](https://github.com/fastapi/fastapi/commit/{sha}) "
        f"\"{git(repo, 'log', '-1', '--format=%s', sha).strip()}\".",
        "",
    ]

    # 1. build
    git(repo, "checkout", "-q", parent)
    (ws / "dakc.toml").write_text(f'[dakc]\nsource_dir = "../fastapi/{DOCS}"\nprovider = "mock"\n', encoding="utf-8")
    section("1. Compile the docs into a knowledge base")
    rep = run("compile", "--json", json_out=True)
    with dakc.open(ws) as kb:
        c = kb.store.counts()
    out += [f"159 documents became {c['passage']:,} passages, {c['claim']:,} claims, {c['page']:,} entity pages, "
            f"{c['summary']} topic summaries and an index, with {c['edges']:,} dependency edges. A full build is "
            f"**{rep['usage']['llm_calls']:,} LLM calls**.", ""]

    # 2. ask before
    section("2. Ask: what happens when a form exceeds FastAPI's parser limits?")
    ask("Before the commit.")

    # 3. apply the commit
    git(repo, "checkout", "-q", sha)
    stat = git(repo, "diff", "--shortstat", parent, sha, "--", DOCS).strip()
    section("3. Apply the real commit", f"`{sha[:8]}` changes the docs: {stat}.")
    run("check")

    # 4. dry run
    section("4. Preview the rebuild (`--dry-run` writes and spends nothing)")
    run("compile", "--dry-run")
    plan = run("compile", "--dry-run", "--json", json_out=True)
    ops = plan["operations"]
    total_pages = c["page"]
    def size(kb: dakc.KnowledgeBase, page: str) -> int:  # pages the plan creates do not exist yet
        try:
            return len(kb.read(page).metadata.get("claim_ids", []))
        except dakc.ArtifactNotFound:
            return 0

    with dakc.open(ws) as kb:  # list the most connected pages first
        regen = sorted(ops.get("regenerate_page", []), key=lambda i: (-size(kb, i), i))
    cut = ops.get("cutoff_page", [])
    mermaid = [
        "```mermaid",
        "flowchart LR",
        f'  D["advanced/request-body-limits.md<br/>1 of 159 documents changed"] --> P["{len(ops.get("reextract", []))} passages '
        f're-extracted<br/>of {c["passage"]:,}"]',
        f'  P --> C["{len(ops.get("new_claim", []))} new claims<br/>{len(ops.get("retract_claim", []))} retracted"]',
        f'  C --> G["{len(regen)} pages regenerated<br/>{", ".join(p.split(":", 1)[1] for p in regen[:6])}'
        f'{" …" if len(regen) > 6 else ""}"]',
        f'  C -.-> K["{len(cut)} pages checked,<br/>unchanged: rebuild stops here"]',
        f'  G --> S["{len(ops.get("regenerate_summary", []))} topic summar{"y" if len(ops.get("regenerate_summary", [])) == 1 else "ies"} regenerated'
        + (f'<br/>{len(ops["rerender_summary"])} re-rendered' if ops.get("rerender_summary") else "") + '"] --> I["index"]',
        f'  U["{total_pages - len(regen) - len(cut):,} other pages<br/>never touched"]',
        "```",
        "",
        f"**{plan['usage']['llm_calls'] + sum(plan['planned_llm_calls'].values()):,} LLM calls planned, against "
        f"{rep['usage']['llm_calls']:,} for a full rebuild.**",
        "",
    ]
    out += mermaid

    # 5. compile
    section("5. Compile incrementally")
    run("compile")

    # 6. ask again and trace
    section("6. Ask again, and trace the answer to its source")
    hits = ask("After the commit.")
    if hits:
        run("trace", hits[0].id)
    with dakc.open(ws) as kb:
        psg = kb.artifacts("passage", query="max_files", limit=3)
    out += [
        "The same commit also documents `max_files` (\"The default is 1,000.\"). That bullet names no capitalized term, "
        "so the free heuristic extractor does not turn it into a claim. It remains findable through full-text passage "
        f"search ({', '.join(f'`{a.id}`' for a in psg) or 'none'}), which is what agents use through the MCP server. "
        "An LLM provider extracts it as a claim.",
        "",
    ]

    # 7. verify
    section("7. Check the result against a from-scratch rebuild")
    run("verify", "--against-full")

    (HERE / "results").mkdir(exist_ok=True)
    (HERE / "results" / "walkthrough.md").write_text("\n".join(out).rstrip() + "\n", encoding="utf-8")
    print(f"wrote {HERE / 'results' / 'walkthrough.md'}")


if __name__ == "__main__":
    main()
